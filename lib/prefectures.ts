/** 都道府県から緯度経度を取得 */
export function getCoordsFromPrefecture(prefecture: string): [number, number] | null {
  const p = prefecture as Prefecture;
  return PREFECTURES.includes(p) ? PREFECTURE_COORDS[p] : null;
}

/** 緯度経度から最も近い都道府県を算出（簡易：庁所在地との距離で比較） */
export function getNearestPrefecture(lat: number, lon: number): Prefecture | null {
  let minDist = Infinity;
  let nearest: Prefecture | null = null;
  for (const pref of PREFECTURES) {
    const [pla, plo] = PREFECTURE_COORDS[pref];
    const dist = (lat - pla) ** 2 + (lon - plo) ** 2;
    if (dist < minDist) {
      minDist = dist;
      nearest = pref;
    }
  }
  return nearest;
}
